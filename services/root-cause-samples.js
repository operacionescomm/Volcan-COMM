function toItem(item) {
  if (Array.isArray(item)) {
    return { nombre: item[0], cantidad: Number(item[1] || 0), tiempo: item[2] == null ? null : Number(item[2]), pct: Number(item[3] || 0) };
  }
  return {
    nombre: String(item.nombre || item.categoria || ''),
    cantidad: Number(item.cantidad || item.cant || 0),
    tiempo: item.tiempo == null ? null : Number(item.tiempo),
    pct: Number(item.pct || item.porcentaje || 0)
  };
}

function normalizeMonth(month) {
  const items = (month.items || []).map(toItem).filter(item => item.nombre);
  const topTen = Number(month.topTen || items.reduce((acc, item) => acc + item.cantidad, 0));
  const totalIncidentes = Number(month.totalIncidentes || topTen || 0);
  const pctTopTen = totalIncidentes > 0 ? topTen / totalIncidentes : 0;
  return { ...month, totalIncidentes, topTen, pctTopTen, items };
}

function normalizeRootCauseCompare(data) {
  const junio = normalizeMonth(data.junio || {});
  const julio = normalizeMonth(data.julio || {});
  const diffTotal = julio.totalIncidentes - junio.totalIncidentes;
  const diffTopTen = julio.topTen - junio.topTen;
  const diffPct = julio.pctTopTen - junio.pctTopTen;
  return { ...data, junio, julio, diffTotal, diffTopTen, diffPct };
}

function getRootCauseComparisonSample(slideNumber) {
  const sample = ROOT_CAUSE_COMPARE_SAMPLES[Number(slideNumber)];
  if (!sample) throw new Error(`No hay muestra Causa Raíz para slide ${slideNumber}`);
  return normalizeRootCauseCompare(sample);
}

function getCerroRootCauseSample() {
  const data = { ...CERRO_ROOT_CAUSE_SAMPLE };
  return { ...data, junio: normalizeMonth(data.junio), julio: normalizeMonth(data.julio) };
}

